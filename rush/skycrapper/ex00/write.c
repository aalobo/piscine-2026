#include <unistd.h>

void affiche_tableau(char **grille)
{
	int	l;
	int	d;
	char	c;

	l= 0;
	while (l < 4)
	{
		d= 0;
		while (d < 4)
		{
			c = grille[l][d] + '0';
			write(1, &c , 1);
			write(1, " ", 1);
			d++;
		}
		l++;
		write(1, "\n", 1);
	}
}
